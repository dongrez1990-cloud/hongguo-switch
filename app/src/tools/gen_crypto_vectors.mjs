// Emit test vectors for the primitives, taken from the reference implementations.
//
// The vendor's abridged "RC4" has no published test vector, so the only honest
// way to check a port of it is to run the reference code and pin its output.
// Standard algorithms (MD5 / SHA-512 / SM3) are checked against their published
// vectors instead -- see hg_crypto_test.c.
//
// Usage: node gen_crypto_vectors.mjs <hongguo.cjs>
//
// Prints C source for the RC4 vector, plus the standard digests computed by
// Node's own crypto so the two can be compared independently.

import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'
import vm from 'node:vm'

// hongguo.cjs is CommonJS and expects `require` to exist in its context; an ESM
// module has no ambient require, so borrow one.
const require = createRequire(import.meta.url)

const [src, outPath] = process.argv.slice(2)
if (!src) {
  console.error('usage: node gen_crypto_vectors.mjs <hongguo.cjs> [out-header]')
  process.exit(2)
}

// When an output path is given, capture stdout and write it ourselves.
// Deliberately NOT left to the caller: PowerShell 5.1's `>` redirection emits
// UTF-16LE by default, which is not valid C and fails at the first line.
if (outPath) {
  const chunks = []
  console.log = (...a) => chunks.push(a.join(' '))
  process.on('exit', () => {
    writeFileSync(outPath, chunks.join('\n') + '\n', 'ascii')
  })
}

const source = readFileSync(src, 'utf8')
const ctx = vm.createContext({ require, Buffer, URL, URLSearchParams, console })
// rc4Gorgon is not part of the oracle's export list, so add it here; AesV3 is a
// class and likewise not exported.
vm.runInContext(source + ';globalThis.rc4Gorgon = rc4Gorgon; globalThis.AesV3 = AesV3;', ctx)

const cbytes = (b) => [...b].map((x) => '0x' + x.toString(16).padStart(2, '0')).join(', ')

// Deterministic input: 20 bytes is exactly the length xGorgon feeds it.
const data = Buffer.from([...Array(20).keys()].map((i) => (i * 7 + 3) & 0xff))
const key = Buffer.from([0x4a, 0x40, 0x16, 0x5a, 0x47, 0x6c, 0x01, 0xa5])
const out = ctx.rc4Gorgon([...data], [...key])

console.log('/* ---- generated by gen_crypto_vectors.mjs from rc4Gorgon ---- */')
console.log(`static const unsigned char RC4V_DATA[${data.length}] = { ${cbytes(data)} };`)
console.log(`static const unsigned char RC4V_KEY[${key.length}]  = { ${cbytes(key)} };`)
console.log(`static const unsigned char RC4V_OUT[${out.length}]  = { ${cbytes(out)} };`)

// ---- AesV3 -------------------------------------------------------------
// All four (timestamp & 3) branches are exercised: the S-box quarter, both
// permutation tables and the initial constant all change with it, so one
// branch passing proves very little.
const AV3_KEY = Buffer.from([...Array(16).keys()].map((i) => (i * 11 + 5) & 0xff))
const AV3_IV = Buffer.from([...Array(16).keys()].map((i) => (i * 13 + 9) & 0xff))
const AV3_SRC = Buffer.from([...Array(256).keys()].map((i) => (i * 29 + 17) & 0xff))

console.log('')
console.log('/* ---- generated from the reference AesV3 class ---- */')
console.log(`static const unsigned char AV3_KEY[16] = { ${cbytes(AV3_KEY)} };`)
console.log(`static const unsigned char AV3_IV[16]  = { ${cbytes(AV3_IV)} };`)
console.log(`static const unsigned char AV3_SRC[256] = {`)
for (let i = 0; i < 256; i += 16) {
  console.log('  ' + cbytes(AV3_SRC.subarray(i, i + 16)) + ',')
}
console.log('};')

for (let word = 0; word < 4; word++) {
  // khronos such that (khronos & 3) === word
  const khronos = 1800500000 + word
  const inst = new ctx.AesV3(AV3_KEY, khronos)
  const res = inst.encrypt(AV3_SRC, AV3_IV)
  console.log(`/* khronos=${khronos} -> word=${khronos & 3}, out length ${res.length} */`)
  console.log(`static const unsigned char AV3_OUT${word}[${res.length}] = {`)
  for (let i = 0; i < res.length; i += 16) {
    console.log('  ' + cbytes(res.subarray(i, i + 16)) + ',')
  }
  console.log('};')
}
console.log('')
console.log('/* ---- standard digests, independently computed by node:crypto ---- */')
for (const s of ['', 'abc', 'The quick brown fox jumps over the lazy dog']) {
  const md5 = createHash('md5').update(s, 'utf8').digest('hex')
  const sha512 = createHash('sha512').update(s, 'utf8').digest('hex')
  console.log(`/* md5("${s}")    = ${md5}`)
  console.log(`   sha512("${s}") = ${sha512} */`)
}
