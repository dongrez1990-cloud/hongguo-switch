// Turn the repo's committed signing.json into a C header.
//
// signing.json is the ground truth this whole port is measured against: 12 rows
// produced by tools/signing-oracle.cjs, each pinning branch/hash/gorgon/helios/
// medusa with a mocked clock and a seeded LCG standing in for Math.random.
//
// The C side must reproduce the SAME random stream, so the seed and generator
// are emitted here too rather than being re-derived by hand at each use site:
// the oracle runs `letSeed = 17` and then consumes draws in field-evaluation
// order (helios first, then medusa), and any mismatch in draw order or count
// silently yields different signatures.
//
// Usage: node gen_sign_vectors.mjs <signing.json> <out-header>

import { readFileSync, writeFileSync } from 'node:fs'

const [src, outPath] = process.argv.slice(2)
if (!src || !outPath) {
  console.error('usage: node gen_sign_vectors.mjs <signing.json> <out-header>')
  process.exit(2)
}

const rows = JSON.parse(readFileSync(src, 'utf8'))
if (!Array.isArray(rows) || rows.length === 0) throw new Error('expected a non-empty array')

const cstr = (s) => {
  let out = '"'
  for (const ch of s) {
    const c = ch.codePointAt(0)
    if (ch === '\\') out += '\\\\'
    else if (ch === '"') out += '\\"'
    else if (c >= 32 && c <= 126) out += ch
    // Octal escapes are exactly three digits, so they cannot bleed into a
    // following digit the way \xNN can in C.
    else if (c <= 255) out += '\\' + c.toString(8).padStart(3, '0')
    else throw new Error(`non-Latin-1 character U+${c.toString(16)} cannot be emitted as a C literal`)
  }
  return out + '"'
}

const fields = ['hash', 'gorgon', 'helios', 'medusa']
for (const f of fields) {
  if (!(f in rows[0])) throw new Error(`row is missing field ${f}`)
}

// Expected shape, asserted so a silently changed oracle cannot slip through.
for (const r of rows) {
  if (r.hash.length !== 40) throw new Error(`hash should be 40 hex chars, got ${r.hash.length}`)
  if (r.gorgon.length !== 52) throw new Error(`gorgon should be 52 hex chars, got ${r.gorgon.length}`)
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(r.helios)) throw new Error('helios is not base64')
  for (const [name, v] of [['hash', r.hash], ['gorgon', r.gorgon]]) {
    if (!/^[0-9a-f]*$/.test(v)) throw new Error(`${name} is not lowercase hex: ${v}`)
  }
}

const lines = []
lines.push('/*')
lines.push(' * GENERATED FILE -- do not edit by hand.')
lines.push(' *')
lines.push(' * From kotlin-tv/core/src/test/resources/signing.json in N3urda/hongguoTV')
lines.push(' * (GPL-3.0), itself generated by tools/signing-oracle.cjs from the GPL-3.0')
lines.push(' * reference in server/vendor/hongguo.cjs. The combined work stays GPL-3.0.')
lines.push(' *')
lines.push(' * Regenerate with:')
lines.push(' *   node gen_sign_vectors.mjs <signing.json> sign_vectors_gen.h')
lines.push(' */')
lines.push('')
lines.push('#ifndef SIGN_VECTORS_GEN_H')
lines.push('#define SIGN_VECTORS_GEN_H')
lines.push('')
lines.push(`#define SV_COUNT ${rows.length}`)
lines.push('')
lines.push('/* Each row is one independently generated request. `body` is NULL when the')
lines.push(' * oracle signed a GET (no body); `body_len` is then 0. */')
lines.push('typedef struct {')
lines.push('  unsigned int  ts;')
lines.push('  const char   *url;')
lines.push('  const char   *body;   /* NULL for a GET */')
lines.push('  unsigned int  body_len;')
lines.push('  const char   *hash;   /* expected hashF13(), hex */')
lines.push('  const char   *gorgon; /* expected xGorgon(), hex */')
lines.push('  const char   *helios; /* expected helios(), base64 */')
lines.push('  const char   *medusa; /* expected medusa header value */')
lines.push('} SignVector;')
lines.push('')
lines.push('static const SignVector SIGN_VECTORS[SV_COUNT] = {')
for (const r of rows) {
  const body = r.body === null || r.body === undefined ? '0' : cstr(r.body)
  const blen = r.body === null || r.body === undefined ? 0 : Buffer.byteLength(r.body, 'utf8')
  lines.push('  {')
  lines.push(`    ${r.ts}u,`)
  lines.push(`    ${cstr(r.url)},`)
  lines.push(`    ${body}, ${blen}u,`)
  lines.push(`    ${cstr(r.hash)},`)
  lines.push(`    ${cstr(r.gorgon)},`)
  lines.push(`    ${cstr(r.helios)},`)
  lines.push(`    ${cstr(r.medusa)},`)
  lines.push('  },')
}
lines.push('};')
lines.push('')
lines.push('/* The oracle seeds the LCG once per row, immediately before computing the')
lines.push(' * row, and then consumes draws in field order (helios, then medusa). A C')
lines.push(' * implementation must reset to 17 at the start of each row. */')
lines.push('#define SV_RNG_SEED 17u')
lines.push('')
lines.push('#endif /* SIGN_VECTORS_GEN_H */')
lines.push('')

writeFileSync(outPath, lines.join('\n'), 'ascii')
console.log(`OK ${outPath}`)
console.log(`  rows: ${rows.length}`)
console.log(`  hash len: ${rows[0].hash.length} hex chars`)
console.log(`  gorgon len: ${rows[0].gorgon.length} hex chars`)
console.log(`  helios len: ${rows[0].helios.length} base64 chars`)
console.log(`  medusa len: ${rows[0].medusa.length} chars`)
console.log(`  bodies: ${rows.filter((r) => r.body).length} with, ${rows.filter((r) => !r.body).length} without`)
