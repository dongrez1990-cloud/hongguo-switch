/*
 * Vector tests for hg_sign.c against the repo's committed signing.json.
 *
 * signing.json is the real acceptance criterion for this port: 12 requests
 * produced by the oracle with a mocked clock and a seeded LCG, each pinning
 * branch / hash / gorgon / helios / medusa. Matching them is the only evidence
 * we have that the C signer agrees with the implementation that actually works
 * against the upstream API.
 *
 * DRAW ORDER IS PART OF THE CONTRACT. The oracle reseeds the LCG to 17 at the
 * start of each row and then consumes draws in field-evaluation order:
 * helios first, then medusa. So the LCG here must be reseeded per row and
 * helios must be the first consumer, or the helios field will not match even
 * though the algorithm is right.
 *
 * medusa is not exercised yet -- see hg_sign.h.
 */

#include "hg_sign.h"
#include "sign_vectors_gen.h"

#include <stdio.h>
#include <string.h>

static int checks = 0;
static int failures = 0;

/* The oracle's Math.random replacement:
 *   letSeed = (Math.imul(letSeed, 1664525) + 1013904223) >>> 0
 * Math.imul is a signed 32-bit multiply, but only the low 32 bits survive the
 * >>> 0, so plain uint32_t wrapping multiplication is the same thing. The
 * returned value equals Math.floor(Math.random() * 2^32). */
static uint32_t g_seed;
static uint32_t lcg(void *user) {
  (void)user;
  g_seed = g_seed * 1664525u + 1013904223u;
  return g_seed;
}

static void expect_str(const char *what, int row, const char *got, const char *want) {
  checks++;
  if (strcmp(got, want) == 0) {
    printf("  PASS  row %2d  %-14s %s\n", row, what, got);
  } else {
    failures++;
    printf("  FAIL  row %2d  %-14s\n        got  %s\n        want %s\n", row, what, got, want);
  }
}

/* A plain boolean check, for assertions that are not "hex string equals". */
static void check(const char *what, int cond) {
  checks++;
  if (cond) {
    printf("  PASS  %-34s\n", what);
  } else {
    failures++;
    printf("  FAIL  %-34s\n", what);
  }
}

#include "branch2_vectors_gen.h"

/* Branch 2. The 12 committed vectors are all branch 0 (the oracle searches
 * tickets until branchOf() == 0), and the reference only avoids branch 1, so in
 * the field requests land on 0 OR 2. These vectors were generated by searching
 * for branch-2 tickets and pinning the reference's own hashF13 output.
 *
 * That makes them weaker evidence than the 60 branch-0 checks: they prove we
 * agree with the reference, not that the reference is right. There is no
 * independent source for a bespoke hash. */
static void test_branch2(void) {
  int i, passed2 = 0;
  printf("\nbranch 2 (%d rows, %s)\n", B2_COUNT,
         "pinned to the reference implementation");
  for (i = 0; i < B2_COUNT; i++) {
    const B2Vector *v = &B2_VECTORS[i];
    const char *qmark = strchr(v->url, '?');
    const char *query = qmark ? qmark + 1 : v->url;
    const uint8_t *body = (const uint8_t *)v->body;
    uint8_t q_sm3[32], b_md5[16];
    char buf[160];
    char label[48];
    uint32_t br;

    if (v->body != NULL) hg_md5(v->body, v->body_len, b_md5);
    else memset(b_md5, 0, sizeof b_md5);
    hg_sm3(query, strlen(query), q_sm3);

    sprintf(label, "b2 row %d is branch 2", i);
    br = hg_branch_of(query, body, v->body_len, v->ts);
    check(label, br == 2);

    sprintf(label, "b2 row %d hashF13", i);
    if (!hg_hash_f13(q_sm3, b_md5, v->ts, buf)) {
      check(label, 0);
    } else {
      int ok = (strcmp(buf, v->hash) == 0);
      if (ok) passed2++;
      check(label, ok);
      if (!ok) printf("        got  %s\n        want %s\n", buf, v->hash);
    }
  }
  printf("  (%d/%d branch-2 rows matched)\n", passed2, B2_COUNT);
}

#include "encode_vectors_gen.h"
#include "hg_request.h"

/* The URL encoder. Pinned to the reference because its output is an INPUT to the
 * signature: one wrong byte changes x-gorgon and x-medusa and the server rejects
 * the request with no useful diagnostic. In particular `*` must survive (Python's
 * quote would escape it) and `!'()` must NOT survive (encodeURIComponent keeps
 * them, then the reference escapes them explicitly). */
static void test_encoder(void) {
  int i, matched = 0;
  printf("\nURL encoder (%d rows, pinned to the reference pythonUrlEncode)\n", ENC_COUNT);
  for (i = 0; i < ENC_COUNT; i++) {
    char buf[1024];
    char label[80];
    const char *want;
    int ok;
    if (i == ENC_MAP_INDEX) continue;          /* the map case needs the device table */
    /* The reference encodes a {q: value} map, so its expected string starts
     * with "q="; hg_url_encode encodes the value alone, so skip those two. */
    want = ENC_VECTORS[i].expected + 2;
    ok = (hg_url_encode(ENC_VECTORS[i].input, buf, sizeof buf) >= 0)
      && (strcmp(buf, want) == 0);
    if (ok) matched++;
    sprintf(label, "enc %02d %s", i, ENC_VECTORS[i].name);
    check(label, ok);
    if (!ok) {
      printf("        got  %s\n        want %s\n", buf, want);
    }
  }
  printf("  (%d/%d encoder rows matched)\n", matched, ENC_COUNT - 1);
}

/* End-to-end request assembly with a REALISTIC query.
 *
 * This test exists because of a bug the 12 vectors could not see: hg_medusa had
 * an internal 80-byte buffer sized from the fixtures, whose URLs carry ~30
 * characters of query. A real device-fingerprint query is 555, so medusa
 * returned 0 for every genuine request while every vector still passed. On the
 * console it appeared as "FAILED to build request: -1".
 *
 * A test that only ever feeds short inputs cannot catch a limit derived from
 * short inputs. So this one assembles a real request and asserts the pieces come
 * out at full size. */
static void test_request(void) {
  static HgRequest req;
  int rc, i, nheaders = 0;
  const char *medusa = NULL;

  printf("\nrequest assembly (realistic query length)\n");

  rc = hg_request_search(&req, "\xe7\x9f\xad\xe5\x89\xa7",
                         1791464625u, 1791464625000ull, 42131u);
  check("hg_request_search succeeds", rc == 0);
  if (rc != 0) return;

  check("query is device-fingerprint length, not fixture length",
        strlen(req.query) > 400);
  check("url is built", strlen(req.url) > 500);

  for (i = 0; req.headers[i] != NULL; i++) {
    nheaders++;
    if (strncmp(req.headers[i], "x-medusa:", 9) == 0) medusa = req.headers[i];
  }
  check("all 14 headers are present", nheaders == 14);
  check("x-medusa was produced at full length",
        medusa != NULL && strlen(medusa) > 1000);

  /* The search endpoint needs the full appSearchParams set. Without them the
   * server answers HTTP 200 with an EMPTY body -- which the console showed as a
   * success with nothing in it, and which is easy to misread as a network fault. */
  check("search sends count",                strstr(req.query, "count=24") != NULL);
  check("search sends offset",               strstr(req.query, "offset=0") != NULL);
  check("search sends tab_type=11",          strstr(req.query, "tab_type=11") != NULL);
  check("search sends bookshelf_search_plan",strstr(req.query, "bookshelf_search_plan=4") != NULL);
  check("search sends use_correct",          strstr(req.query, "use_correct=true") != NULL);
  check("search sends user_is_login",        strstr(req.query, "user_is_login=0") != NULL);

  /* APP_DEVICE overrides must REPLACE, not append: a duplicated key would change
   * the signed query string and is not what the reference sends.
   *
   * Anchored on "&version_code=", not "version_code=": manifest_version_code and
   * update_version_code both CONTAIN the shorter string, so a naive search counts
   * three matches and reports a duplicate that is not there. */
  {
    const char *p = req.query;
    int hits = 0;
    while ((p = strstr(p, "&version_code=")) != NULL) { hits++; p++; }
    check("version_code appears exactly once", hits == 1);
    check("version_code carries the APP value",
          strstr(req.query, "&version_code=72232") != NULL);
    check("version_name carries the APP value",
          strstr(req.query, "&version_name=7.2.2.32") != NULL);
  }

  if (medusa != NULL) {
    printf("        query=%u url=%u headers=%d medusa=%u\n",
           (unsigned)strlen(req.query), (unsigned)strlen(req.url),
           nheaders, (unsigned)strlen(medusa));
  }

  /* The video-model path must keep working too. */
  rc = hg_request_video_model(&req, "7001", 1791464625u, 1791464625000ull, 1u);
  check("hg_request_video_model succeeds", rc == 0);
  check("video model sends a POST body", rc == 0 && req.body_len > 100);

  /* ---- THE ROUTE AND THE PARAMETER NAME ARE THE WHOLE FIX (build156) ---------------------------
   *
   * The batched route answers {"Code":110001} to every request that reaches it -- signed, unsigned,
   * and signature-deliberately-corrupted all give the same 125 bytes -- which is why the plan
   * request failed with rc=-5 for a whole round no matter what the body said. The route that
   * answers carries ONE video per request and takes `video_id`, as a JSON STRING: sending the id as
   * a number is refused with HTTP 400 "expected string".
   *
   * These four lines pin exactly that, because both halves are silent if they drift: a URL back to
   * the dead route, or a body that stops carrying video_id, would each look like an upstream outage
   * from the console rather than like a regression in this file. */
  check("the video model call goes to the one-video route",
        rc == 0 && strstr(req.url, "/novel/player/video_model/v1/") != NULL);
  check("and NOT to the retired batched route",
        rc == 0 && strstr(req.url, "multi_video_model") == NULL);
  check("the body carries video_id as a JSON string",
        rc == 0 && strstr(req.body, "\"video_id\":\"7001\"") != NULL);
  check("and the batched mixed_video_id_map is gone",
        rc == 0 && strstr(req.body, "mixed_video_id_map") == NULL);
}

int main(void) {
  int i;
  printf("hg_sign tests against signing.json (%d rows)\n", SV_COUNT);
  printf("sizeof(long)=%d  sizeof(void*)=%d\n\n", (int)sizeof(long), (int)sizeof(void *));

  for (i = 0; i < SV_COUNT; i++) {
    const SignVector *v = &SIGN_VECTORS[i];
    const char *qmark = strchr(v->url, '?');
    const char *query = qmark ? qmark + 1 : v->url;
    const uint8_t *body = (const uint8_t *)v->body;
    uint8_t q_sm3[32], b_md5[16];
    char buf[160];
    char b64[HG_HELIOS_MAX];
    char medusa[1600];

    if (v->body != NULL) hg_md5(v->body, v->body_len, b_md5);
    else memset(b_md5, 0, sizeof b_md5);
    hg_sm3(query, strlen(query), q_sm3);

    /* The vectors were generated by searching tickets until branchOf() == 0,
     * so every row must be branch 0 -- and only branch 0 is implemented. */
    {
      uint32_t br = hg_branch_of(query, body, v->body_len, v->ts);
      checks++;
      if (br == 0) {
        printf("  PASS  row %2d  %-14s %u\n", i, "branchOf", br);
      } else {
        failures++;
        printf("  FAIL  row %2d  %-14s got %u, want 0\n", i, "branchOf", br);
      }
    }

    /* hashF13 */
    if (!hg_hash_f13(q_sm3, b_md5, v->ts, buf)) {
      failures++;
      checks++;
      printf("  FAIL  row %2d  %-14s refused (branch != 0)\n", i, "hashF13");
    } else {
      expect_str("hashF13", i, buf, v->hash);
    }

    /* xGorgon, with the reference's constant nonce 42131 */
    hg_xgorgon(query, body, v->body_len, v->ts, 42131u, buf);
    expect_str("xGorgon", i, buf, v->gorgon);

    /* helios -- reseed here, because in the oracle this is the row's first draw */
    g_seed = SV_RNG_SEED;
    if (!hg_helios(v->ts, lcg, NULL, b64, sizeof b64)) {
      failures++;
      checks++;
      printf("  FAIL  row %2d  %-14s returned 0\n", i, "helios");
    } else {
      expect_str("helios", i, b64, v->helios);
    }

    /* medusa -- continues the SAME stream, so it must not be reseeded. In the
     * oracle helios is evaluated before medusa, leaving medusa draws #2..#6. */
    if (!hg_build_medusa(v->url, body, v->body_len, v->ts, lcg, NULL,
                         medusa, sizeof medusa)) {
      failures++;
      checks++;
      printf("  FAIL  row %2d  %-14s returned 0\n", i, "medusa");
    } else {
      expect_str("medusa", i, medusa, v->medusa);
    }
  }

  test_encoder();
  test_branch2();
  test_request();

  printf("\n%d checks, %d failure(s)\n", checks, failures);
  return failures == 0 ? 0 : 1;
}
